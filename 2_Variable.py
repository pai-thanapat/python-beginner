# 2. Variable

# String
first_name = "Bro"
food = "Pizza"
email = "Bro123@fake.com"

print(f"Hello {first_name}")
print(f"I like {food}")
print(f"My email is: {email}")

# Intiger
age = 21
quantity = 3
num_of_items = 5

print(f"My age is {age} years old")
print(f"You are buying {quantity} items")
print(f"Total items: {num_of_items}")

# Float
price = 9.99
gpa = 3.5
distance = 5.5

print(f"The price is ${price}")
print(f"My GPA is {gpa}")
print(f"You ran {distance} kilometers today")

# Boolean
is_student = True
is_teacher = False

print(f"Am I a student? {is_student}")
print(f"Are you a teacher?")

if is_teacher:
    print("You are a teacher")
else:
    print("You are not a teacher")
